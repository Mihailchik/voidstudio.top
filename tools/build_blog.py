def article_url(article):
    return f"{SITE}/blog/{article['slug']}.html"


def render_article(article):
    e = escape
    url = article_url(article)
    ld = {
        "@context": "https://schema.org",
        "@graph": [
            {
                "@type": "BlogPosting", "@id": url + "#article", "url": url,
                "mainEntityOfPage": url, "headline": article["title"],
                "description": article["description"], "inLanguage": "ru-RU",
                "datePublished": article["date"], "dateModified": article["date"],
                "image": SITE + "/assets/img/og.png",
                "author": {"@id": SITE + "/#organization"},
                "publisher": {"@id": SITE + "/#organization"},
            },
            {
                "@type": "BreadcrumbList",
                "itemListElement": [
                    {"@type": "ListItem", "position": 1, "name": "Void Studio", "item": SITE + "/"},
                    {"@type": "ListItem", "position": 2, "name": "Блог", "item": SITE + "/blog/"},
                    {"@type": "ListItem", "position": 3, "name": article["short"], "item": url},
                ],
            },
        ],
    }
    service = article["service"]
    others = "".join(
        f'<a class="post-link" href="/blog/{a["slug"]}.html"><span>{e(a["short"])}</span><span aria-hidden="true">→</span></a>'
        for a in ARTICLES if a["slug"] != article["slug"]
    )
    return (
        head(f"{article.get('seo_title', article['title'])} — Void Studio", article["description"], url, "article", ld)
        + f"""<main>
<article class="post">
<header class="post-head"><p class="kicker"><a href="/blog/">Блог</a> · <time datetime="{article['date']}">{human_date(article['date'])}</time></p><h1>{e(article['title'])}</h1><p class="post-lead">{e(article['lead'])}</p></header>
<div class="post-body">{article['body']}</div>
<aside class="post-service"><p class="kicker">Услуга по теме</p><a href="/{service}.html">{SERVICE_NAMES[service]} →</a><p>Расскажите о задаче — предложим решение.</p><a class="button primary" href="{TELEGRAM}" target="_blank" rel="noopener">Написать в Telegram ↗</a></aside>
</article>
<section class="post-more"><p class="kicker">Ещё в блоге</p><div>{others}</div></section>
</main>
"""
        + FOOT
    )


def render_index():
    e = escape
    url = SITE + "/blog/"
    description = "Статьи Void Studio о разработке сайтов, приложений, Telegram-ботов и автоматизации. Объясняем на примерах собственных проектов."
    ld = {
        "@context": "https://schema.org", "@type": "Blog", "@id": url + "#blog", "url": url,
        "name": "Блог Void Studio", "description": description, "inLanguage": "ru-RU",
        "publisher": {"@id": SITE + "/#organization"},
        "blogPost": [{"@type": "BlogPosting", "headline": a["title"], "url": article_url(a), "datePublished": a["date"]} for a in ARTICLES],
    }
    rows = "".join(
        f'<article class="post-row"><time datetime="{a["date"]}">{human_date(a["date"])}</time>'
        f'<h2><a href="/blog/{a["slug"]}.html">{e(a["short"])}</a></h2><p>{e(a["description"])}</p></article>'
        for a in sorted(ARTICLES, key=lambda a: a["date"], reverse=True)
    )
    return (
        head("Блог Void Studio — сайты, приложения, боты и автоматизация", description, url, "website", ld)
        + f"""<main>
<section class="blog-hero"><p class="kicker">Блог</p><h1>Как это устроено.</h1><p>Пишем о сайтах, приложениях, ботах и автоматизации. Объясняем на своих проектах, которые можно открыть и проверить.</p></section>
<section class="post-list">{rows}</section>
</main>
"""
        + FOOT
    )


def main():
    out = ROOT / "blog"
    out.mkdir(exist_ok=True)
    (out / "index.html").write_text(render_index(), encoding="utf-8")
    print("blog/index.html")
    for article in ARTICLES:
        (out / f"{article['slug']}.html").write_text(render_article(article), encoding="utf-8")
        print(f"blog/{article['slug']}.html")


if __name__ == "__main__":
    main()
